import { useEffect, useState } from 'react';
import { useNavigate, useParams } from 'react-router-dom';

import {
  getTicketById,
  selfHeal,
  overrideTicket,
  askMore,
  escalateTicket,
} from '../services/ticketService';

import ConfidenceMeter from '../components/ConfidenceMeter';
import HighlightedArticle from '../components/HighlightedArticle';
import LoadingState from '../components/LoadingState';
import ErrorState from '../components/ErrorState';
import AskMoreModal from '../components/modals/AskMoreModal';
import SelfHealModal from '../components/modals/SelfHealModal';
import { useRole } from '../context/RoleContext';
import { hasPermission, ROLE_HOME } from '../config/permissions';

import {
  getWorkflowStage,
  isAmbiguousScore,
  STAGE_LABELS,
} from '../utils/workflow';

export default function TicketDetail() {
  const { id } = useParams();
  const navigate = useNavigate();
  const { role } = useRole();
  const canTriage = hasPermission(role, 'PERFORM_TICKET_ACTIONS');
  const dashboardHome = ROLE_HOME[role] || '/login';

  const [ticket, setTicket] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  const [actionLoading, setActionLoading] = useState(false);
  const [actionMessage, setActionMessage] = useState('');
  const [askMoreOpen, setAskMoreOpen] = useState(false);
  const [selfHealOpen, setSelfHealOpen] = useState(false);

  const loadTicket = async () => {
    try {
      setLoading(true);
      setError('');

      const data = await getTicketById(id);

      if (!data) {
        setError('Ticket not found.');
        return;
      }

      setTicket(data);
    } catch (err) {
      setError('Unable to load ticket.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadTicket();
  }, [id]);

  if (loading) {
    return <LoadingState label="Loading ticket…" />;
  }

  if (error) {
    return (
      <ErrorState
        message={error}
        onRetry={loadTicket}
      />
    );
  }

  if (!ticket) {
    return null;
  }

  const hasScore = ticket.score !== null && ticket.score !== undefined;
  const stage = hasScore ? getWorkflowStage(ticket.score) : null;
  const ambiguous = hasScore ? isAmbiguousScore(ticket.score) : false;

  const handleSelfHeal = async () => {
    try {
      setActionLoading(true);
      setActionMessage('');

      const updated = await selfHeal(ticket.id);
      setTicket(updated);
      setActionMessage('Self-healing action completed.');
    } catch (err) {
      setActionMessage('Self-healing action failed.');
    } finally {
      setActionLoading(false);
    }
  };

  const handleEscalate = async () => {
    try {
      setActionLoading(true);
      setActionMessage('');

      const updated = await escalateTicket(ticket.id);
      setTicket(updated);
      setActionMessage('Ticket escalated to Production Support.');
    } catch (err) {
      setActionMessage('Escalation failed.');
    } finally {
      setActionLoading(false);
    }
  };

  const handleOverride = async () => {
    const note = window.prompt(
      'Enter a short analyst override note:'
    );

    if (!note) {
      return;
    }

    try {
      setActionLoading(true);
      setActionMessage('');

      const updated = await overrideTicket(
        ticket.id,
        note
      );

      setTicket(updated);
      setActionMessage('Analyst override recorded.');
    } catch (err) {
      setActionMessage('Override failed.');
    } finally {
      setActionLoading(false);
    }
  };

  const handleAskMore = async (answers) => {
    try {
      setActionLoading(true);
      setActionMessage('');

      const updated = await askMore(
        ticket.id,
        answers
      );

      setTicket(updated);
      setAskMoreOpen(false);

      setActionMessage(
        'Clarification answers recorded. Re-matching can be connected to the backend.'
      );
    } catch (err) {
      setActionMessage(
        'Unable to save clarification answers.'
      );
    } finally {
      setActionLoading(false);
    }
  };

  return (
    <div className="page">
      <div className="page-header">
        <div>
          <button
            className="btn btn-secondary"
            onClick={() => navigate(dashboardHome)}
          >
            ← Back to Dashboard
          </button>

          <h1>Ticket {ticket.id}</h1>

          <p>
            Department: <strong>{ticket.department}</strong>
          </p>
        </div>

        <div className="ticket-hash-placeholder">
          SHA-256 ticket hash:
          <code title={ticket.rawSha256}>{ticket.rawSha256 ? `${ticket.rawSha256.slice(0, 24)}…` : 'Generated by backend'}</code>
        </div>
      </div>

      <section className="detail-card">
        <h2>Ticket Description</h2>

        <p className="ticket-full-description">
          {ticket.description}
        </p>
      </section>

      {!hasScore && (
        <section className="detail-card">
          <div className="state-block state-empty">
            This ticket is awaiting AI-assisted matching. Confidence, the
            matched article, and decision actions will appear here once
            the backend matcher has scored it.
          </div>
        </section>
      )}

      {hasScore && (
        <section className="detail-card">
          <ConfidenceMeter score={ticket.score} />

          <div className="workflow-stage">
            Workflow decision:{' '}
            <strong>{STAGE_LABELS[stage]}</strong>
          </div>

          {ambiguous && (
            <div className="confidence-warning">
              The score is exactly 80%. This boundary requires
              mentor clarification before the final workflow
              behavior is confirmed.
            </div>
          )}
        </section>
      )}

      {hasScore && ticket.score >= 95 && ticket.article && (
        <section className="detail-card">
          <h2>Matched Knowledge Article</h2>

          <h3>{ticket.article.title}</h3>

          <HighlightedArticle
            content={ticket.article.content}
            matchingFragments={ticket.article.matchingFragments}
          />
        </section>
      )}

      {hasScore && (
        <section className="detail-card">
          <h2>Decision</h2>

          {!canTriage && (
            <p className="ticket-table__view-only">
              Your role ({role}) has read-only access. Decision actions
              are available to Analyst and Admin roles.
            </p>
          )}

          {canTriage && (
            <div className="decision-actions">
              {stage === 'SELF_HEAL' && (
                ticket.status === 'SELF_HEALED' || ticket.status === 'RESOLVED' ? (
                  <button
                    className="btn btn-secondary"
                    disabled
                    style={{ opacity: 0.6, cursor: 'not-allowed' }}
                  >
                    Self-Healed ✓
                  </button>
                ) : (
                  <button
                    className="btn btn-primary"
                    onClick={() => setSelfHealOpen(true)}
                    disabled={actionLoading}
                  >
                    {actionLoading ? 'Executing…' : 'Self-Heal'}
                  </button>
                )
              )}

              {stage === 'OVERRIDE' && (
                ticket.status === 'OVERRIDDEN' ? (
                  <button
                    className="btn btn-secondary"
                    disabled
                    style={{ opacity: 0.6, cursor: 'not-allowed' }}
                  >
                    Overridden ✓
                  </button>
                ) : (
                  <button
                    className="btn btn-primary"
                    onClick={handleOverride}
                    disabled={actionLoading}
                  >
                    {actionLoading ? 'Saving…' : 'Analyst Override'}
                  </button>
                )
              )}

              {stage === 'ASK_MORE' && (
                <button
                  className="btn btn-primary"
                  onClick={() => setAskMoreOpen(true)}
                  disabled={actionLoading}
                >
                  Ask More
                </button>
              )}

              {stage === 'ESCALATE' && (
                ticket.status === 'ESCALATED' ? (
                  <button
                    className="btn btn-secondary"
                    disabled
                    style={{ opacity: 0.6, cursor: 'not-allowed' }}
                  >
                    Already Escalated
                  </button>
                ) : (
                  <button
                    className="btn btn-danger"
                    onClick={handleEscalate}
                    disabled={actionLoading}
                  >
                    {actionLoading
                      ? 'Escalating…'
                      : 'Escalate to Production Support'}
                  </button>
                )
              )}
            </div>
          )}

          {actionMessage && (
            <p className="action-message">
              {actionMessage}
            </p>
          )}
        </section>
      )}

      <AskMoreModal
        isOpen={askMoreOpen}
        questions={ticket.questions || []}
        onClose={() => setAskMoreOpen(false)}
        onConfirm={handleAskMore}
        loading={actionLoading}
      />
      <SelfHealModal
        isOpen={selfHealOpen}
        onClose={() => setSelfHealOpen(false)}
        onConfirm={handleSelfHeal}
        loading={actionLoading}
      />
    </div>
  );
}